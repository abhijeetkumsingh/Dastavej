"""PDF report for resume analysis (ReportLab, Latin text)."""
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

GREEN, DEEP, BORDER, MINT = colors.HexColor("#008F55"), colors.HexColor("#064E3B"), colors.HexColor("#DDE9E1"), colors.HexColor("#E5F5EC")


def _s(t):
    return escape(str(t).encode("latin-1", "replace").decode("latin-1"))


def build_report(r, out_path):
    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontName="Helvetica", fontSize=9.5, leading=13, textColor=colors.HexColor("#17211C"))
    small = ParagraphStyle("s", parent=body, fontSize=8, textColor=colors.HexColor("#64736A"))
    h1 = ParagraphStyle("h1", parent=body, fontName="Helvetica-Bold", fontSize=20, textColor=DEEP, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=body, fontName="Helvetica-Bold", fontSize=12.5, textColor=GREEN, spaceBefore=12, spaceAfter=4)
    doc = SimpleDocTemplate(str(out_path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title="DASTAVEJ Resume Analysis")
    st = [Paragraph("DASTAVEJ - Resume Analysis", h1), Paragraph(f"Target role: <b>{_s(r['role'])}</b>", body), Spacer(1, 4)]
    st.append(Paragraph(f"Estimated ATS compatibility: <b>{r['score']}/100</b> ({_s(r['score_label'])})", ParagraphStyle("sc", parent=body, fontSize=14, textColor=DEEP)))
    st.append(Paragraph(_s(r["disclaimer"]), small))
    st.append(Paragraph("Score breakdown", h2))
    rows = [["Component", "Score", "Why"]]
    for b in r["breakdown"]:
        rows.append([Paragraph(_s(b["name"]), body), f"{b['score']} / {b['max']}", Paragraph(_s(" ".join(b["notes"][:3])), small)])
    t = Table(rows, colWidths=[42 * mm, 22 * mm, 108 * mm])
    t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), MINT), ("GRID", (0, 0), (-1, -1), 0.4, BORDER), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 9)]))
    st.append(t)

    def bullets(title, items):
        if not items:
            return
        st.append(Paragraph(title, h2))
        for i in items:
            st.append(Paragraph("&bull; " + _s(i), body))

    sk = r["skills"]
    bullets("Skills found", [", ".join(sk["found"]) or "None detected"])
    bullets("Missing core skills", [", ".join(sk["missing_required"]) or "None - good coverage"])
    bullets("Missing nice-to-have skills", [", ".join(sk["missing_optional"])] if sk["missing_optional"] else [])
    if r.get("jd_match"):
        j = r["jd_match"]
        bullets("Job description match", [f"Keywords matched: {j['match_percent_keywords']}%", f"Skills matched: {j['match_percent_skills']}%",
                                          "Missing keywords: " + (", ".join(j["missing_keywords"][:12]) or "none")])
    bullets("Top improvements", r["suggestions"][:12])
    bullets("Recommended projects", r["recommendations"]["projects"])
    bullets("Courses", r["recommendations"]["courses"])
    bullets("Certifications", r["recommendations"]["certifications"])
    st.append(Paragraph("Career roadmap", h2))
    for ph in r["roadmap"]:
        st.append(Paragraph(f"<b>{_s(ph['phase'])}</b>", body))
        for a in ph["actions"]:
            st.append(Paragraph("&bull; " + _s(a), body))
    st.append(Spacer(1, 10))
    st.append(Paragraph("Generated by DASTAVEJ on your device-side server. Your resume was analysed locally; no AI service was used for this report.", small))
    doc.build(st)
